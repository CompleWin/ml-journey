function dots(parent) {
  const seen = new Array(30).fill(0);
  return BIN.map(b => {
    const j = seen[b]++;
    return circle(TX(TE0 + (b + .5) * BW), TB - (j + .5) * DY, 9, { class: 'fill c0', stroke: 'none', ...(parent ? { parent } : {}) });
  });
}

function twCurve() {
  let d = '';
  TWF.forEach((f, i) => { d += (i ? 'L' : 'M') + TX(-4.2 + i * .1).toFixed(1) + ',' + (TB - KD * f).toFixed(1); });
  return path(d, { class: 'c1', 'stroke-width': 5 });
}

function twBase() {
  twAxis();
  tex(800, 130, '\\dfrac{\\hat\\lambda_{max} - \\lambda_+}{s}', { size: 42 });
  const ds = dots();
  twCurve();
  label(TX(-3.1), 520, 'TW₁', { class: 'c1' });
  return ds;
}

