function fitPath() {
  const a = Math.log10(NT / N);
  return `M${PX(VMIN).toFixed(1)},${PY(a).toFixed(1)}L${PX(-2.784).toFixed(1)},${PY(a - (ALPHA - 1) * (-2.784 - VMIN)).toFixed(1)}`;
}

